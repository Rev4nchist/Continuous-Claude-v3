#!/usr/bin/env bash
#
# Cloud Agent install phase for Continuous Claude v3.
#
# Idempotent repository bootstrap: system packages, Python deps, TypeScript
# hooks, Playwright browser, local DB config, and a provisioned PostgreSQL +
# pgvector database. Safe to run repeatedly.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT"

log() { printf '\n=== %s ===\n' "$*"; }

# ---------------------------------------------------------------------------
# 1. System packages: PostgreSQL 16 + pgvector (Docker-free memory backend)
# ---------------------------------------------------------------------------
if ! dpkg -s postgresql-16 >/dev/null 2>&1 \
   || ! dpkg -s postgresql-16-pgvector >/dev/null 2>&1; then
  log "Installing PostgreSQL 16 + pgvector"
  sudo apt-get update -qq
  sudo DEBIAN_FRONTEND=noninteractive apt-get install -y -qq \
    postgresql-16 postgresql-16-pgvector postgresql-client-16
else
  log "PostgreSQL 16 + pgvector already installed"
fi

# ---------------------------------------------------------------------------
# 2. uv (Python package/venv manager)
# ---------------------------------------------------------------------------
export PATH="$HOME/.local/bin:$PATH"
if ! command -v uv >/dev/null 2>&1; then
  log "Installing uv"
  curl -LsSf https://astral.sh/uv/install.sh | sh
  export PATH="$HOME/.local/bin:$PATH"
else
  log "uv already installed ($(uv --version))"
fi

# ---------------------------------------------------------------------------
# 3. Python dependencies for the opc toolkit (memory system, scripts)
# ---------------------------------------------------------------------------
log "Syncing Python dependencies (opc, postgres extra)"
cd "$REPO_ROOT/opc"
uv sync --extra postgres

# ---------------------------------------------------------------------------
# 4. TypeScript hooks: install deps + build to dist/*.mjs
#    NOTE: on Linux x64, npm optimizes node_modules/esbuild/bin/esbuild into a
#    native binary, so the repo's `node node_modules/esbuild/bin/esbuild`
#    script fails. Invoke the esbuild binary directly instead.
# ---------------------------------------------------------------------------
log "Installing + building TypeScript hooks"
cd "$REPO_ROOT/.claude/hooks"
npm install
# Defensive: restore the tracked package.json if an install side effect removed it.
if [ ! -f package.json ]; then
  git -C "$REPO_ROOT" checkout -- .claude/hooks/package.json
fi
node_modules/.bin/esbuild src/*.ts --bundle --platform=node --format=esm \
  --outdir=dist --out-extension:.js=.mjs --external:better-sqlite3 \
  --banner:js="import{createRequire as __hookCreateRequire}from'module';const require=__hookCreateRequire(import.meta.url);"

# ---------------------------------------------------------------------------
# 5. Root JS deps + Playwright browser (E2E tests)
# ---------------------------------------------------------------------------
log "Installing root JS deps + Playwright chromium"
cd "$REPO_ROOT"
npm install
npx --yes playwright install --with-deps chromium

# ---------------------------------------------------------------------------
# 6. Authoritative local DB config (opc/.env is gitignored)
# ---------------------------------------------------------------------------
ENV_FILE="$REPO_ROOT/opc/.env"
if [ ! -f "$ENV_FILE" ]; then
  log "Writing opc/.env"
  cat > "$ENV_FILE" <<'EOF'
# Generated by .cursor/install.sh for the Cloud Agent environment.
OPC_POSTGRES_URL=postgresql://claude:claude_dev@localhost:5432/continuous_claude
DATABASE_URL=postgresql://claude:claude_dev@localhost:5432/continuous_claude
AGENTICA_MEMORY_BACKEND=postgres
EMBEDDING_PROVIDER=local
EOF
else
  log "opc/.env already present"
fi

# ---------------------------------------------------------------------------
# 7. Provision the database (start server, create role/db/schema)
# ---------------------------------------------------------------------------
log "Provisioning PostgreSQL database"
bash "$REPO_ROOT/.cursor/start.sh"
bash "$REPO_ROOT/.cursor/init-db.sh"

# Leave the cluster stopped so environment builds snapshot a clean data dir;
# start.sh brings it back up on every boot.
log "Stopping PostgreSQL for a clean snapshot"
sudo pg_ctlcluster 16 main stop || true

log "Install complete"
