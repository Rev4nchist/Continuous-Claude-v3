<#
.SYNOPSIS
  Generate git conditional-include rules so commits in Fourth work directories are
  authored with the Fourth email, from accounts.json as the single source.

.WHY
  Commit identity is the one identity layer that is PERMANENT. gh auth can be
  re-pointed, a remote URL can be edited, a credential can be replaced -- but the
  author email is baked into the commit object, and changing it later means
  rewriting history and breaking every SHA. So this is the layer to get right
  BEFORE work lands, not after.

  Verified 2026-08-05: 14 work-routed directories would author as
  dkhayes44@gmail.com. accounts.json has named this script as the remedy since
  d0c3cf8; it did not exist.

.DESIGN
  Three files, so that regenerating is never a merge against hand-edited config:

    ~/.gitconfig                     ONE include line, added once, idempotent
    ~/.gitconfig-fourth.routes       generated: one includeIf per work route
    ~/.gitconfig-fourth.identity     generated: the [user] block

  Generated files are rewritten wholesale every run; ~/.gitconfig is only ever
  appended to, and only if the include line is absent. Nothing hand-written is
  parsed or regenerated -- the failure mode this avoids is the lossy
  parse-and-rewrite that has damaged other managed files in this repo.

.WINDOWS
  - `gitdir/i:` not `gitdir:` -- case-INSENSITIVE matching. Windows hands you
    both cases for the same path depending on who produced it, and a
    case-sensitive rule silently stops matching.
  - Forward slashes, and a TRAILING SLASH. Without the trailing slash the
    condition matches the directory itself but not repositories inside it.
  - Paths containing spaces are fine: the condition lives inside a quoted
    subsection name. Three routes here have spaces.

.EXAMPLE
  pwsh -File scripts/github/apply-commit-identity.ps1            # show plan only
  pwsh -File scripts/github/apply-commit-identity.ps1 -Apply

.NOTES
  ASCII only (PS 5.1 CP1252 parse trap on UTF-8 punctuation in strings).
#>
[CmdletBinding()]
param([switch]$Apply)

$ErrorActionPreference = 'Stop'
$AccountsPath  = Join-Path $PSScriptRoot 'accounts.json'
$GitConfig     = Join-Path $HOME '.gitconfig'
$RoutesFile    = Join-Path $HOME '.gitconfig-fourth.routes'
$IdentityFile  = Join-Path $HOME '.gitconfig-fourth.identity'

$cfg  = Get-Content $AccountsPath -Raw | ConvertFrom-Json
$personal = $cfg.accounts.personal
if (-not $personal) { throw "accounts.json has no personal account" }
$work = $cfg.accounts.work
$routes = @($cfg.routes | Where-Object { $_.commitAccount -eq 'work' })
if (-not $work -or -not $routes.Count) {
  Write-Host ""
  Write-Host "apply-commit-identity   personal only ($($personal.email)); no work account"
  Write-Host "nothing to generate. Commit identity stays the personal account."
  exit 0
}

# Git wants forward slashes and a trailing slash; ~ is expanded by git itself but
# we hand it absolute paths, so normalise here rather than relying on that.
function To-GitDir([string]$p) {
  $n = ($p -replace '\\', '/').TrimEnd('/')
  return "$n/"
}

Write-Host ""
Write-Host "apply-commit-identity   -> $($work.email)  (name: $($work.user))"
Write-Host ("mode: " + $(if ($Apply) { 'APPLY' } else { 'PLAN ONLY (no writes)' }))
Write-Host ""
Write-Host "=== routes ($($routes.Count)) ==="
$missing = 0
foreach ($r in $routes) {
  $exists = Test-Path $r.prefix
  if (-not $exists) { $missing++ }
  Write-Host ("  {0}  {1}" -f $(if ($exists) { '[ok]     ' } else { '[absent] ' }), (To-GitDir $r.prefix))
}
if ($missing) {
  Write-Host ""
  Write-Host "  note: $missing route prefix(es) do not exist on disk. A condition that"
  Write-Host "        matches nothing is harmless -- it simply never fires -- but it also"
  Write-Host "        silently protects nothing, so do not read its presence as coverage."
}

if (-not $Apply) {
  Write-Host ""
  Write-Host "PLAN ONLY. Re-run with -Apply to write:"
  Write-Host "  $IdentityFile   (generated)"
  Write-Host "  $RoutesFile     (generated)"
  Write-Host "  $GitConfig      (append one include line, only if absent)"
  exit 0
}

# --- generated: identity ----------------------------------------------------
@"
# GENERATED by scripts/github/apply-commit-identity.ps1 -- do not hand-edit.
# Source of truth: continuous-claude/scripts/github/accounts.json
[user]
	name = $($work.user)
	email = $($work.email)
"@ | Set-Content $IdentityFile -Encoding utf8NoBOM
Write-Host ""
Write-Host "wrote $IdentityFile"

# --- generated: routes ------------------------------------------------------
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("# GENERATED by scripts/github/apply-commit-identity.ps1 -- do not hand-edit.")
[void]$sb.AppendLine("# One conditional include per commitAccount=work route in accounts.json.")
[void]$sb.AppendLine("# gitdir/i: is case-insensitive on purpose; trailing slash is required to")
[void]$sb.AppendLine("# match repositories INSIDE the directory, not just the directory itself.")
foreach ($r in $routes) {
  [void]$sb.AppendLine("")
  if ($r.note) { [void]$sb.AppendLine("# $($r.note)") }
  [void]$sb.AppendLine("[includeIf `"gitdir/i:$(To-GitDir $r.prefix)`"]")
  [void]$sb.AppendLine("	path = $($IdentityFile -replace '\\','/')")
}
$sb.ToString() | Set-Content $RoutesFile -Encoding utf8NoBOM
Write-Host "wrote $RoutesFile  ($($routes.Count) conditions)"

# --- ~/.gitconfig: append the include ONCE ----------------------------------
$routesForward = $RoutesFile -replace '\\', '/'
$existing = if (Test-Path $GitConfig) { Get-Content $GitConfig -Raw } else { '' }
if ($existing -match [regex]::Escape($routesForward)) {
  Write-Host "$GitConfig already includes the routes file (no change)"
} else {
  $block = "`n[include]`n	path = $routesForward`n"
  Add-Content -Path $GitConfig -Value $block -Encoding utf8NoBOM
  Write-Host "appended include to $GitConfig"
}

# --- verify by ASKING GIT, per directory ------------------------------------
# The only claim worth making is what git actually resolves from inside each
# directory, because that is what resolves includeIf. Reading the files back
# proves nothing about whether the conditions match.
Write-Host ""
Write-Host "=== verification (git config user.email, asked from inside each dir) ==="
$bad = 0; $checked = 0
foreach ($r in $routes) {
  if (-not (Test-Path $r.prefix)) { continue }
  $checked++
  $got = ((& git -C $r.prefix config user.email 2>&1) -join '').Trim()
  if ($got -eq $work.email) { Write-Host ("  [ok]   {0}  {1}" -f $got, $r.prefix) }
  else { $bad++; Write-Host ("  [FAIL] got '{0}' expected '{1}'  {2}" -f $got, $work.email, $r.prefix) }
}
$home_email = ((& git -C $HOME config user.email 2>&1) -join '').Trim()
Write-Host ""
Write-Host "  control: $HOME resolves to '$home_email' (should stay personal)"
if ($home_email -eq $work.email) {
  Write-Host "  [FAIL] the work identity leaked to the personal catch-all -- a condition is too broad."
  $bad++
}

Write-Host ""
if ($bad) { Write-Host "FAIL  $bad of $checked checked director(ies) wrong"; exit 1 }
Write-Host "PASS  $checked director(ies) author as $($work.email); personal default intact"
Write-Host "History is NOT rewritten. Existing commits keep dkhayes44@gmail.com -- add that"
Write-Host "address as a verified secondary email on the $($work.user) GitHub account if you"
Write-Host "want past commits to attribute to it (no rewrite, no SHA churn)."
